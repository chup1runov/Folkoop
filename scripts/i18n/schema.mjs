export function flattenI18n(value,prefix='',out=new Map()){
  for(const [key,item] of Object.entries(value||{})){
    const path=prefix?prefix+'.'+key:key;
    if(item&&typeof item==='object'&&!Array.isArray(item))flattenI18n(item,path,out);
    else out.set(path,item);
  }
  return out;
}

export function validateI18nBundle(bundle){
  const leaves=flattenI18n(bundle);
  const actual=[...leaves.keys()].sort();
  const required=FOLKOOP_I18N_PATHS;
  const requiredSet=new Set(required);
  const actualSet=new Set(actual);
  const missing=required.filter(path=>!actualSet.has(path));
  const extra=actual.filter(path=>!requiredSet.has(path));
  const invalid=actual.filter(path=>{
    const value=leaves.get(path);
    return typeof value!=='string'||value.trim().length===0;
  });
  return Object.freeze({
    ok:missing.length===0&&extra.length===0&&invalid.length===0,
    missing:Object.freeze(missing),
    extra:Object.freeze(extra),
    invalid:Object.freeze(invalid)
  });
}
