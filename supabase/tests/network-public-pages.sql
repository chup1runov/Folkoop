-- Synthetic accounts and rollback: never publishes an existing participant.
\set ON_ERROR_STOP on
begin;
create schema fk_page_test;
grant usage on schema fk_page_test to anon,authenticated;
create function fk_page_test.ok(value boolean,label text) returns void language plpgsql as $$ begin if value is distinct from true then raise exception 'FAIL: %',label;end if;raise notice 'PASS: %',label;end $$;
create function fk_page_test.denied(statement text) returns boolean language plpgsql as $$begin execute statement;return false;exception when others then return true;end $$;
insert into auth.users(id) values('11111111-1111-4111-8111-111111111111'),('22222222-2222-4222-8222-222222222222');
insert into folkoop_private.pilots(user_id) values('11111111-1111-4111-8111-111111111111'),('22222222-2222-4222-8222-222222222222');
set local role authenticated;
select set_config('request.jwt.claim.sub','11111111-1111-4111-8111-111111111111',true);
select public.fk_save_profile('Page test owner','Private skill','Private account',true);
select fk_page_test.ok((select count(*)=0 from public.fk_public_pages),'directory listing is not internet publication');
select public.fk_save_public_page(0,true,'{"name":"QA public alias","about":"Visible text","ideas":"PRIVATE DRAFT"}',array['name','about']);
select fk_page_test.ok(public.fk_my_public_page()->>'revision'='1','owner sees own editing state');
select fk_page_test.ok(fk_page_test.denied($q$select public.fk_save_public_page(0,true,'{"name":"Stale"}',array['name'])$q$),'stale update rejected');
select fk_page_test.ok(fk_page_test.denied($q$select public.fk_save_public_page(1,true,'{"name":"Bad","messages":"secret"}',array['name'])$q$),'unknown fields rejected');
select set_config('request.jwt.claim.sub','22222222-2222-4222-8222-222222222222',true);
select public.fk_save_profile('Second owner','','',false);
select fk_page_test.ok(public.fk_my_public_page()->>'revision'='0','second account cannot read owner draft');
select fk_page_test.ok(fk_page_test.denied($q$update public.fk_public_pages set content='{}'$q$),'direct foreign write denied');
select fk_page_test.ok(fk_page_test.denied('select * from folkoop_private.profile_pages'),'private editing table inaccessible');
set local role anon;
select fk_page_test.ok((select content='{"name":"QA public alias","about":"Visible text"}'::jsonb from public.fk_public_pages limit 1),'anonymous receives exact selected projection');
select fk_page_test.ok(fk_page_test.denied('select * from public.fk_profiles'),'account profiles still private');
select fk_page_test.ok(fk_page_test.denied('select public.fk_my_public_page()'),'anonymous cannot access drafts');
select fk_page_test.ok(fk_page_test.denied($q$select public.fk_save_public_page(1,false,'{}','{}')$q$),'anonymous cannot change publication');
set local role authenticated;
select set_config('request.jwt.claim.sub','11111111-1111-4111-8111-111111111111',true);
select public.fk_save_public_page(1,false,'{"name":"QA public alias","ideas":"PRIVATE DRAFT"}',array['name']);
select fk_page_test.ok(public.fk_my_public_page()->'content'->>'ideas'='PRIVATE DRAFT','unpublishing preserves private editing content');
set local role anon;
select fk_page_test.ok((select count(*)=0 from public.fk_public_pages),'unpublished page absent for anonymous');
set local role authenticated;
select set_config('request.jwt.claim.sub','11111111-1111-4111-8111-111111111111',true);
select public.fk_save_public_page(2,true,'{"name":"QA public alias"}',array['name']);
reset role;
delete from public.fk_profiles where id='11111111-1111-4111-8111-111111111111';
select fk_page_test.ok((select count(*)=0 from public.fk_public_pages),'profile closure cascades public page');
select fk_page_test.ok((select count(*)=0 from folkoop_private.profile_pages),'profile closure cascades private page');
rollback;
